#!/usr/bin/env python3
"""Emit Unicode category ranges used by the GPT-2 pretokenizer.

Ranges match the `regex` module (not the stdlib `re` module):
  letters    \\p{L}
  numbers    \\p{N}
  whitespace \\s
"""

import pathlib
import sys

import regex
import unicodedata

OUT = pathlib.Path(__file__).resolve().parents[1] / "src" / "unicode_tables.inc"


def ranges_for(pred):
    spans = []
    start = None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            spans.append((start, cp))
            start = None
    if start is not None:
        spans.append((start, 0x110000))
    return spans


def is_letter(cp):
    return regex.match(r"\p{L}", chr(cp)) is not None


def is_number(cp):
    return regex.match(r"\p{N}", chr(cp)) is not None


def is_space(cp):
    return regex.match(r"\s", chr(cp)) is not None


def emit(name, spans, fh):
    fh.write(f"static constexpr CpRange {name}[] = {{\n")
    for a, b in spans:
        fh.write(f"    {{{a}u, {b}u}},\n")
    fh.write("};\n")
    fh.write(f"static constexpr int {name}Count = {len(spans)};\n\n")


def main():
    letters = ranges_for(is_letter)
    numbers = ranges_for(is_number)
    spaces = ranges_for(is_space)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8") as fh:
        fh.write("// Generated by scripts/gen_unicode_tables.py\n")
        fh.write(f"// regex {regex.__version__}, unicodedata {unicodedata.unidata_version}\n")
        fh.write("// Each range is half-open: [begin, end).\n")
        fh.write("// letters: \\\\p{L}, numbers: \\\\p{N}, whitespace: \\\\s, as matched by the regex module.\n\n")
        emit("kLetterRanges", letters, fh)
        emit("kNumberRanges", numbers, fh)
        emit("kSpaceRanges", spaces, fh)
    print(f"wrote {OUT}")
    print(f"letters {len(letters)} numbers {len(numbers)} spaces {len(spaces)}")


if __name__ == "__main__":
    sys.exit(main())
